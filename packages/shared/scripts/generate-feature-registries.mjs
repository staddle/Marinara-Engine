import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const srcDir = join(root, "src");

const TOOL_ORDER = [
  "roll-dice",
  "update-game-state",
  "set-expression",
  "trigger-event",
  "search-lorebook",
  "web-search",
  "save-lorebook-entry",
  "read-chat-summary",
  "append-chat-summary",
  "read-chat-variable",
  "write-chat-variable",
  "update-about-me",
  "spotify-get-current-playback",
  "spotify-get-playlists",
  "spotify-get-playlist-tracks",
  "spotify-search",
  "spotify-play",
  "spotify-set-volume",
];

async function readManifestFolders(baseDir, manifestFile = "manifest.ts") {
  const entries = await readdir(baseDir, { withFileTypes: true });
  const manifests = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const manifestPath = join(baseDir, entry.name, manifestFile);
    let text = "";
    try {
      text = await readFile(manifestPath, "utf8");
    } catch {
      continue;
    }
    const match = text.match(/export\s+const\s+([A-Za-z0-9_]+)\s*=/);
    if (!match?.[1]) {
      throw new Error(`Could not find exported manifest const in ${manifestPath}`);
    }
    manifests.push({ folder: entry.name, exportName: match[1] });
  }

  return manifests;
}

function sortByPreferredOrder(manifests, preferredOrder) {
  const order = new Map(preferredOrder.map((folder, index) => [folder, index]));
  return manifests.sort((a, b) => {
    const aOrder = order.get(a.folder);
    const bOrder = order.get(b.folder);
    if (aOrder !== undefined && bOrder !== undefined) return aOrder - bOrder;
    if (aOrder !== undefined) return -1;
    if (bOrder !== undefined) return 1;
    return a.folder.localeCompare(b.folder);
  });
}

const manifests = sortByPreferredOrder(
  await readManifestFolders(join(srcDir, "features", "function-calls", "tools")),
  TOOL_ORDER,
);
const lines = [
  "// This file is generated by packages/shared/scripts/generate-feature-registries.mjs.",
  "// Add a new folder with manifest.ts, then run pnpm --filter @marinara-engine/shared build.",
  'import type { ToolDefinition } from "./tool-definitions.js";',
  "",
  ...manifests.map(({ folder, exportName }) => `import { ${exportName} } from "./tools/${folder}/manifest.js";`),
  "",
  "export const BUILT_IN_TOOLS: ToolDefinition[] = [",
  ...manifests.map(({ exportName }) => `  ${exportName},`),
  "];",
  "",
];

await writeFile(join(srcDir, "features", "function-calls", "tool-registry.generated.ts"), `${lines.join("\n")}\n`, "utf8");
